-- 阶段 4：用户长期记忆（为「每个用户」建立可检索、可注入的记忆）
--
-- 目标口径：
--   1) 记忆归属于「某家单位里的某个账号」，归属键 = (company_id, owner_username)。
--      username 在单位内唯一（ADR-M006），company_id 是全项目统一的软隔离维度（ADR-M002），
--      因此这套键既能做到「每个用户一份记忆」，又不越过单位边界。
--   2) 记忆按类型分档：EPISODIC（情景：做过什么）/ SEMANTIC（语义：事实与偏好）/ PROCEDURAL（程序：做事方式）。
--      分档是为了注入提示词时能分组呈现，而不是把所有碎片揉成一段。
--   3) content_hash 让「同一用户、同一类型、同一内容」在数据库层面唯一——重复记录直接拒绝，
--      去重不靠应用层「先查后写」的竞态窗口。
--
-- 纪律：
--   1) 语句全部幂等，可重复执行；
--   2) company_id / owner_username NOT NULL —— 漏填的插入当场失败，不许静默变成「谁都不见」；
--   3) 不留未使用列：本表每一列都被 MemoryService / MemoryContextBuilder 实际读取或写入。

-- ---------------------------------------------------------------------------
-- 1) 用户记忆表
-- ---------------------------------------------------------------------------
create table if not exists user_memory (
  id              bigint generated by default as identity primary key,
  -- 数据归属单位（org_unit.type='COMPANY' 行）：与其它公司维度表同口径，绝不为空
  company_id      bigint       not null,
  -- 记忆归属账号（登录名，来自 JWT sub）；同一单位内唯一，跨单位可重名
  owner_username  varchar(64)  not null,
  -- 记忆类型：EPISODIC / SEMANTIC / PROCEDURAL
  memory_type     varchar(16)  not null,
  -- 记忆正文（自然语言一句话/一段话）
  content         text         not null,
  -- 正文归一化后的 SHA-256（十六进制 64 位）：用于「同人同类型同内容」去重
  content_hash    varchar(64)  not null,
  -- 重要度 0..100：越大越优先被检索与注入（默认 50）
  importance      integer      not null default 50,
  -- 记忆来源：MANUAL（用户在记忆管理里手写）/ AGENT（AI 会话中沉淀）
  source          varchar(32)  not null default 'MANUAL',
  created_at      timestamp    not null default current_timestamp,
  -- 更新时间同时是检索打分的「新鲜度」依据
  updated_at      timestamp    not null default current_timestamp,
  -- 过期时间：非空且已过期的记忆不再参与检索（仍保留在管理列表里可见）
  expires_at      timestamp,
  constraint ck_user_memory_type
    check (memory_type in ('EPISODIC', 'SEMANTIC', 'PROCEDURAL')),
  constraint ck_user_memory_importance
    check (importance between 0 and 100),
  constraint ck_user_memory_content_not_blank
    check (length(btrim(content)) > 0),
  constraint ck_user_memory_source
    check (source in ('MANUAL', 'AGENT'))
);

-- 去重唯一键：同一单位、同一账号、同一类型下，同一份内容只允许一行
create unique index if not exists ux_user_memory_owner_content
  on user_memory (company_id, owner_username, memory_type, content_hash);

-- 检索/列表主路径：按「某单位某人」取记忆，按更新时间倒序
create index if not exists idx_user_memory_owner_updated
  on user_memory (company_id, owner_username, updated_at desc);

-- 过期过滤
create index if not exists idx_user_memory_expires
  on user_memory (expires_at);

comment on table user_memory is '用户长期记忆：归属键 (company_id, owner_username)，按类型分档，content_hash 保证同人同类型不重复（阶段 4）';
comment on column user_memory.memory_type is 'EPISODIC 情景 / SEMANTIC 语义 / PROCEDURAL 程序';
comment on column user_memory.importance is '重要度 0..100，参与检索打分';
comment on column user_memory.expires_at is '过期时间，非空且已过期则不参与检索';

-- ---------------------------------------------------------------------------
-- 2) 自检
-- ---------------------------------------------------------------------------
do $$
declare
  n bigint;
begin
  select count(*) into n from information_schema.columns
   where table_name = 'user_memory' and column_name = 'company_id' and is_nullable = 'NO';
  if n <> 1 then
    raise exception 'V16 失败：user_memory.company_id 必须存在且为 NOT NULL';
  end if;

  select count(*) into n from information_schema.columns
   where table_name = 'user_memory' and column_name = 'owner_username' and is_nullable = 'NO';
  if n <> 1 then
    raise exception 'V16 失败：user_memory.owner_username 必须存在且为 NOT NULL';
  end if;

  select count(*) into n from information_schema.columns
   where table_name = 'user_memory' and column_name = 'content_hash' and is_nullable = 'NO';
  if n <> 1 then
    raise exception 'V16 失败：user_memory.content_hash 必须存在且为 NOT NULL';
  end if;

  select count(*) into n from pg_indexes
   where tablename = 'user_memory' and indexname = 'ux_user_memory_owner_content';
  if n <> 1 then
    raise exception 'V16 失败：缺少去重唯一索引 ux_user_memory_owner_content';
  end if;

  raise notice 'V16 ok: user_memory 已建（company_id + owner_username NOT NULL，content_hash 去重）';
end $$;

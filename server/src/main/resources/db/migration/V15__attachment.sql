-- 阶段 3 任务 2：统一文件与附件服务（中台「货架」能力之一，ADR-M011）
-- 目标口径（方案 §3.2「统一文件与附件」）：上传/下载鉴权 + 下载审计，文件落本地磁盘，存储根可配置。
--
-- 设计：
--   file_attachment  附件元数据表：一个附件一行，记录原始名 / 存储名 / 相对路径 / 大小 / 类型 / 归属业务。
--   文件本体落本地磁盘（storage_path 只存相对 storage-root 的路径，绝不存绝对路径，便于迁移）。
--   归属口径：company_id NOT NULL（与公司维度表同口径，ADR-M002 软隔离）；业务侧再按 biz_type+biz_id 关联具体单据。
--
-- 纪律：
--   1) 语句全部幂等，可重复执行；
--   2) company_id NOT NULL —— 文件归属单位，跨公司访问被应用层 canAccessCompany 拒绝（见 AttachmentService）；
--   3) storage_path 只存相对路径，挂载点/磁盘根由 application.yml 的 WORKBENCH_FILE_ROOT 决定，
--      换盘或容器化时只改配置、不动数据。

-- ---------------------------------------------------------------------------
-- 1) 附件元数据表
-- ---------------------------------------------------------------------------
create table if not exists file_attachment (
  id            bigint generated by default as identity primary key,
  -- 数据归属单位（org_unit.type='COMPANY' 行）；与 11 张公司维度表同口径，绝不为空。
  company_id    bigint        not null,
  -- 关联业务：biz_type 标识模块（如 LEAVE/PAYROLL/RECEPTION），biz_id 标识具体单据
  biz_type      varchar(32)   not null,
  biz_id        varchar(64)   not null,
  -- 原始文件名（用户上传时的名字，仅展示用，不参与路径，避免路径穿越）
  original_name varchar(255)  not null,
  -- 落盘文件名：UUID + 原始扩展名（无扩展名则无后缀），避免重名覆盖与中文/特殊字符问题
  stored_name   varchar(128)  not null,
  -- 相对 storage-root 的路径，如 1/uuid.pdf；绝不存绝对路径
  storage_path  varchar(512)  not null,
  content_type  varchar(128)  not null,
  size_bytes    bigint        not null,
  -- 上传人（登录名），用于审计与"我的上传"
  created_by    varchar(64)   not null,
  created_at    timestamp     not null default current_timestamp,
  constraint ck_file_attachment_size_nonneg check (size_bytes >= 0)
);

create index if not exists idx_file_attachment_company on file_attachment (company_id);
create index if not exists idx_file_attachment_biz on file_attachment (biz_type, biz_id);

comment on table file_attachment is '附件元数据：文件本体落本地磁盘，storage_path 只存相对 storage-root 的路径（阶段 3 任务 2，ADR-M011）';

-- ---------------------------------------------------------------------------
-- 2) 自检
-- ---------------------------------------------------------------------------
do $$
declare
  n bigint;
begin
  select count(*) into n from information_schema.columns
   where table_name = 'file_attachment' and column_name = 'company_id';
  if n <> 1 then
    raise exception 'V15 失败：file_attachment.company_id 列缺失';
  end if;
  -- company_id 必须 NOT NULL（跨公司隔离的硬约束，由应用层 canAccessCompany 把关）
  perform 1 from information_schema.columns
   where table_name = 'file_attachment' and column_name = 'company_id' and is_nullable = 'NO';
  if not found then
    raise exception 'V15 失败：file_attachment.company_id 必须为 NOT NULL';
  end if;
  raise notice 'V15 ok: file_attachment 已建（company_id NOT NULL，storage_path 相对路径）';
end $$;

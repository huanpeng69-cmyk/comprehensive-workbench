-- 组织机构：公司 / 项目部 / 部门三级树
create table org_unit (
  id         bigint generated by default as identity primary key,
  name       varchar(64)  not null,
  type       varchar(16)  not null,
  parent_id  bigint,
  full_path  varchar(64),
  sort_no    integer,
  enabled    boolean      not null
);

-- 用户账号
create table sys_user (
  id              bigint generated by default as identity primary key,
  username        varchar(32)  not null unique,
  name            varchar(64)  not null,
  password_hash   varchar(120) not null,
  org_id          bigint,
  project_id      bigint,
  phone           varchar(20),
  employment_type varchar(16),
  enabled         boolean      not null
);

-- 角色
create table sys_role (
  id          bigint generated by default as identity primary key,
  code        varchar(32) not null unique,
  name        varchar(32) not null,
  data_scope  varchar(16) not null,
  enabled     boolean     not null
);

-- 用户-角色关联
create table sys_user_role (
  user_id bigint not null,
  role_id bigint not null,
  primary key (user_id, role_id)
);

-- 审计日志：敏感操作留痕
create table audit_log (
  id          bigint generated by default as identity primary key,
  username    varchar(32)  not null,
  action      varchar(64)  not null,
  target_type varchar(64),
  target_id   varchar(64),
  detail      text,
  created_at  timestamp    not null default now()
);

create index idx_org_unit_parent on org_unit (parent_id);
create index idx_sys_user_project on sys_user (project_id);
create index idx_audit_log_user on audit_log (username, created_at);

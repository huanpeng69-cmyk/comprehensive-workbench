-- 阶段 3：统一文号生成（中台「货架」能力之一，ADR-M009）
-- 目标口径（方案 §3.2「统一字典与编码」）：类别 + 年度 + 序号，不重号、不跳号。
--
-- 设计（两表分工）：
--   code_rule      规则表：一个「类别」一条规则，定义文号格式与重置周期。人可读、可后台维护。
--   code_sequence  序号表：一个 (类别, 周期值) 一行，只存 current_value，是唯一有并发争用的地方。
--
-- 为什么不合并成一张表：
--   规则是低频读、几乎不改；序号是高频写、有并发争用。拆开后「改规则」不会因为序号行锁而互相阻塞，
--   也让「取号」这条热路径只碰一张小表（索引命中 (category, period)，行锁粒度最细）。
--
-- 纪律：
--   1) 语句全部幂等，可重复执行；
--   2) 序号表不设 company_id —— 文号是「公司级」编号（类别 + 年度全局唯一），
--      与 salary_config 保持全局单行的理由一致（方案 §9.1 结论 2）；单位维度由调用方在
--      业务数据上落 company_id，不进入编号本身；
--   3) current_value 只允许服务端递增（SELECT ... FOR UPDATE），任何手工改值都会破坏不重号承诺。

-- ---------------------------------------------------------------------------
-- 1) 规则表
-- ---------------------------------------------------------------------------
create table if not exists code_rule (
  id            bigint generated by default as identity primary key,
  -- 类别码：调用方传的 key，全局唯一（同一套文号规则公司统一制定，不允许各单位各造一套）
  category      varchar(32)  not null unique,
  -- 类别名称，仅用于展示
  name          varchar(64)  not null,
  -- 格式模板，占位符：{PREFIX} 前缀 / {YYYY} 四位年 / {YY} 两位年 / {SEQ} 序号 / {PERIOD} 周期值
  pattern       varchar(128) not null,
  -- 序号位数：补零宽度，如 4 → 0001
  seq_width     integer      not null default 4,
  -- 重置周期：YEAR（每年归 1）/ NONE（一直递增）
  reset_cycle   varchar(16)  not null default 'YEAR',
  enabled       boolean      not null default true,
  constraint ck_code_rule_seq_width check (seq_width between 1 and 10),
  constraint ck_code_rule_reset_cycle check (reset_cycle in ('YEAR', 'NONE'))
);

comment on table code_rule is '文号规则：类别 + 格式模板 + 序号宽度 + 重置周期（阶段 3，ADR-M009）';

-- ---------------------------------------------------------------------------
-- 2) 序号表：(category, period) 唯一，period 为当前周期值（YEAR 周期即四位年份）
-- ---------------------------------------------------------------------------
create table if not exists code_sequence (
  id            bigint generated by default as identity primary key,
  category      varchar(32)  not null,
  period        varchar(16)  not null,
  current_value bigint       not null default 0,
  updated_at    timestamp    not null default current_timestamp,
  constraint uq_code_sequence_category_period unique (category, period),
  constraint ck_code_sequence_value_nonneg check (current_value >= 0)
);

create index if not exists idx_code_sequence_category on code_sequence (category);

comment on table code_sequence is '文号序号：一个 (类别, 周期) 一行，仅由服务端 SELECT FOR UPDATE 递增（阶段 3，ADR-M009）';

-- ---------------------------------------------------------------------------
-- 3) 种子规则：只放「演示与回归用」的最小集合，真实业务规则由后台按需添加
--    刻意不放 demo 数据到序号表：序号表第一行应在第一次真实取号时创建，
--    避免种子数据把首个业务编号顶高（也是「不跳号」承诺的一部分）。
-- ---------------------------------------------------------------------------
insert into code_rule (category, name, pattern, seq_width, reset_cycle, enabled)
select * from (values
  ('LEAVE',   '请假单',   '{PREFIX}-{YYYY}-{SEQ}', 4, 'YEAR', true),
  ('PAYROLL', '工资发放', '{PREFIX}-{YYYY}-{SEQ}', 4, 'YEAR', true),
  ('RECEPTION','公务接待', '{PREFIX}-{YYYY}-{SEQ}', 4, 'YEAR', true),
  ('CONDOLENCE','慰问金',  '{PREFIX}-{YYYY}-{SEQ}', 4, 'YEAR', true)
) as v(category, name, pattern, seq_width, reset_cycle, enabled)
 where not exists (select 1 from code_rule r where r.category = v.category);

-- ---------------------------------------------------------------------------
-- 4) 自检
-- ---------------------------------------------------------------------------
do $$
declare
  n_rule bigint;
begin
  select count(*) into n_rule from code_rule;
  if n_rule < 4 then
    raise exception 'V12 失败：code_rule 应至少有 4 条种子规则，实际 % 条', n_rule;
  end if;
  raise notice 'V12 ok: 文号规则 % 条（序号表 % 行，应在首次取号时才写入）',
    n_rule, (select count(*) from code_sequence);
end $$;

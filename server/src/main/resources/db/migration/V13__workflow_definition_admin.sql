-- 阶段 3 任务 4：流程定义后台配置化（第一步：定义/节点可管理 + 版本化 + 审计，ADR-M010）
-- 目标口径（方案 §3.2「统一流程与待办」）：把 WorkflowDataSeeder 的硬编码定义变成可管理的配置数据。
--
-- 设计（三步走的第二步的前置，本期只做第一步）：
--   1) 给定义/节点补「描述」列，让后台能向管理员解释每个字段的含义；
--   2) 新增 process_definition_version 快照表：每次改定义都存一份完整快照（定义 + 全部节点），
--      可回退。快照用 JSON 存，避免为历史版本再建一张节点表；
--   3) 权限与审计由代码侧负责（@PreAuthorize + audit_log），不在 SQL 层做。
--
-- 纪律：
--   1) 语句全部幂等，可重复执行；
--   2) 不给 process_definition / process_node 加 company_id —— 三家单位共用一套定义
--      （ADR-M002 / 方案 §9.1 结论 2），加公司列会让"谁改定义"变成跨单位扯皮；
--   3) 快照表只增不改不删：历史版本是审计依据，回滚靠"把旧快照写回当前定义"实现，
--      而不是删掉中间版本。

-- ---------------------------------------------------------------------------
-- 1) 定义表补描述列
-- ---------------------------------------------------------------------------
alter table process_definition add column if not exists description varchar(256);

comment on column process_definition.description is '流程定义说明：向管理员解释该流程的用途（阶段 3，ADR-M010）';

-- ---------------------------------------------------------------------------
-- 2) 节点表补描述列
-- ---------------------------------------------------------------------------
alter table process_node add column if not exists description varchar(256);

comment on column process_node.description is '节点说明：向管理员解释该节点的审批口径（阶段 3，ADR-M010）';

-- ---------------------------------------------------------------------------
-- 3) 定义版本快照表：一个 (定义, 版本号) 一行，snapshot 为「定义 + 全部节点」的 JSON
-- ---------------------------------------------------------------------------
create table if not exists process_definition_version (
  id            bigint generated by default as identity primary key,
  definition_id bigint       not null,
  version       integer      not null,
  -- 变更类型：INIT 初始发布 / UPDATE 修改 / ROLLBACK 回滚产生的新版本
  change_type   varchar(16)  not null,
  -- 变更说明（管理员填写，回滚时用于记录"为什么退回"）
  change_note   varchar(256),
  -- 完整快照：{ definition: {...}, nodes: [...] }，字段与当前表结构一致
  snapshot      text         not null,
  created_by    varchar(64)  not null,
  created_at    timestamp    not null default current_timestamp,
  constraint uq_pd_version_definition_version unique (definition_id, version),
  constraint ck_pd_version_number_pos check (version > 0),
  constraint fk_pd_version_definition foreign key (definition_id)
      references process_definition (id) on delete cascade
);

create index if not exists idx_pd_version_definition on process_definition_version (definition_id, version desc);

comment on table process_definition_version is '流程定义版本快照：每次改动存一份完整 JSON，可回退（阶段 3，ADR-M010）';

-- ---------------------------------------------------------------------------
-- 4) 自检
-- ---------------------------------------------------------------------------
do $$
declare
  n_col_def bigint;
  n_col_node bigint;
begin
  select count(*) into n_col_def
    from information_schema.columns
   where table_schema = 'public' and table_name = 'process_definition' and column_name = 'description';
  if n_col_def <> 1 then
    raise exception 'V13 失败：process_definition.description 列未建成';
  end if;

  select count(*) into n_col_node
    from information_schema.columns
   where table_schema = 'public' and table_name = 'process_node' and column_name = 'description';
  if n_col_node <> 1 then
    raise exception 'V13 失败：process_node.description 列未建成';
  end if;

  raise notice 'V13 ok: 定义/节点描述列就位，版本快照表已建（当前 % 个版本）',
    (select count(*) from process_definition_version);
end $$;

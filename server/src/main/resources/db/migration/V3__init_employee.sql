-- 人员花名册（Phase 2 数据中心化 · 第一批：员工模块）
-- 敏感字段：id_card / phone / monthly_pay —— Phase 3 将增加权限与脱敏
create table employee (
  id              bigint generated by default as identity primary key,
  seq             integer      not null default 0,
  name            varchar(64)  not null,
  gender          varchar(8),
  id_card         varchar(32),
  phone           varchar(20),
  age             integer,
  join_date       varchar(20),
  employment_type varchar(16),
  education       varchar(16),
  school          varchar(64),
  major           varchar(64),
  title           varchar(64),
  political       varchar(16),
  position        varchar(64),
  admin_series    varchar(32),
  prof_series     varchar(16),
  salary_mechanism varchar(16),
  salary_grade    varchar(32),
  monthly_pay     numeric(12,2),
  first_adjust    varchar(16),
  project_id      bigint,
  project         varchar(64),
  status          varchar(32),
  certificates    varchar(255),
  contract_rel    varchar(32),
  category        varchar(16),
  created_at      timestamp    not null default now(),
  updated_at      timestamp    not null default now()
);

create index idx_employee_project on employee (project_id);
create index idx_employee_name on employee (name);

-- 工资制作（Phase 2 第二批 · 最敏感模块）
-- 整个模块仅 COMPANY 数据范围角色可读写（Service 层强制 + 审计）。
-- NumLike（number | "=公式" 字符串）统一存 varchar，保留公式能力。

create table salary_month (
  id          bigint generated by default as identity primary key,
  month       varchar(7)  not null unique,
  imported_at timestamp   not null default now()
);

create table salary_record (
  id             varchar(64) primary key,      -- 月份-姓名 组合键（与前端一致）
  month          varchar(7)  not null,
  department     varchar(64),
  seq            integer,
  name           varchar(64) not null,
  salary_grade   varchar(32),
  post_days      varchar(64),
  post_salary    varchar(64),
  title_allowance varchar(64),
  ot_days        varchar(64),
  overtime       varchar(64),
  bonus          varchar(64),
  make_up        varchar(64),
  seniority      varchar(64),
  site_allowance varchar(64),
  due_total      varchar(64),
  pension        varchar(64),
  unemployment   varchar(64),
  medical        varchar(64),
  housing_fund   varchar(64),
  annuity        varchar(64),
  large_medical  varchar(64),
  other_deduct   varchar(64),
  child_edu      varchar(64),
  continuing_edu varchar(64),
  housing_loan   varchar(64),
  housing_rent   varchar(64),
  elderly_care   varchar(64),
  infant_care    varchar(64),
  tax            varchar(64),
  tax_adjust     varchar(64),
  deduct         varchar(64),
  net_total      varchar(64),
  month_perf     varchar(64),
  union_fee      varchar(64),
  sign           varchar(64),
  imported_due   numeric(14,2),
  imported_net   numeric(14,2)
);

create index idx_salary_record_month on salary_record (month);

create table perf_record (
  id             varchar(64) primary key,
  month          varchar(7)  not null,
  seq            integer,
  department     varchar(64),
  name           varchar(64) not null,
  month_score    varchar(32),
  perf_level     varchar(32),
  incentive_coef varchar(32),
  sep_perf       varchar(64),
  aug_base       varchar(64),
  incentive_part varchar(64),
  balance_coef   varchar(32),
  coop_coef      varchar(32),
  final_incentive varchar(64),
  total_perf     varchar(64)
);

create index idx_perf_record_month on perf_record (month);

-- 工资核算配置：应出工日基准 + 薪档标准表（整体 JSON 存取）
create table salary_config (
  id    integer primary key default 1,
  data  text not null
);

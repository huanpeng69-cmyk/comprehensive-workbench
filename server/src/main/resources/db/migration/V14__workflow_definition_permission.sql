-- 阶段 3 任务 4：流程定义管理权限点（ADR-M010）
-- 背景：后台可改流程定义后，"谁能改"直接决定审批路由。写操作必须有权限点把关，
--       否则任何登录用户都能改全公司共用的流程定义（一次误操作可让审批流瘫痪）。
--
-- 设计：
--   sys_permission   权限点字典：一个权限点一行，人可读、可后台维护；
--   sys_role_permission 角色 ↔ 权限点：本期只把 workflow:definition:manage 授给 SYSTEM_ADMIN。
--
-- 为什么不复用"只有 SYSTEM_ADMIN 能进后台"的约定：
--   那个约定没有代码承载（SecurityConfig 只有 anyRequest().authenticated()），
--   等于没有拦截。权限点落到表里 + @PreAuthorize 校验，才是真把关；
--   同时为阶段 4「权限点表 + 菜单/按钮下发」预留数据模型，不必再改表。
--
-- 纪律：
--   1) 语句全部幂等，可重复执行；
--   2) 权限点 code 全局唯一（与 sys_role.code 同口径：公司统一制定）；
--   3) 不给权限点加 company_id —— 权限是全局口径，数据隔离靠 company_id（ADR-M002）。

-- ---------------------------------------------------------------------------
-- 1) 权限点字典
-- ---------------------------------------------------------------------------
create table if not exists sys_permission (
  id          bigint generated by default as identity primary key,
  code        varchar(64)  not null unique,
  name        varchar(64)  not null,
  -- 权限点分组：仅用于后台展示归类
  module      varchar(32),
  enabled     boolean      not null default true
);

comment on table sys_permission is '权限点字典：后台写操作的准入门槛（阶段 3，ADR-M010）';

-- ---------------------------------------------------------------------------
-- 2) 角色 ↔ 权限点
-- ---------------------------------------------------------------------------
create table if not exists sys_role_permission (
  role_id       bigint not null,
  permission_id bigint not null,
  primary key (role_id, permission_id),
  constraint fk_srp_role foreign key (role_id) references sys_role (id) on delete cascade,
  constraint fk_srp_permission foreign key (permission_id) references sys_permission (id) on delete cascade
);

comment on table sys_role_permission is '角色 ↔ 权限点：本期只授 SYSTEM_ADMIN 管理流程定义（阶段 3，ADR-M010）';

-- ---------------------------------------------------------------------------
-- 3) 种子：本期唯一的权限点
-- ---------------------------------------------------------------------------
insert into sys_permission (code, name, module, enabled)
select 'workflow:definition:manage', '流程定义管理', 'workflow', true
 where not exists (select 1 from sys_permission where code = 'workflow:definition:manage');

-- ---------------------------------------------------------------------------
-- 4) 授予：刻意不在这里做
--    sys_role 的角色种子由 DataInitializer（Spring 启动期的 CommandLineRunner）写入，
--    Flyway 跑本脚本时 sys_role 还是空的，这条 insert 永远匹配不到行、纯属空转，
--    还会给人一种"授权已生效"的错觉。
--    真正的授权在 DataInitializer#grantDefinitionManage（角色就绪后幂等补授），
--    开发库/生产库这类已有 SYSTEM_ADMIN 角色的库同样由它兜住。
-- ---------------------------------------------------------------------------

-- ---------------------------------------------------------------------------
-- 5) 自检
-- ---------------------------------------------------------------------------
-- 自检只验证「迁移自己该做的事」：权限点必须建成。
-- 刻意不断言「SYSTEM_ADMIN 已获得该权限」——sys_role 的角色种子由 DataInitializer
-- （Spring 启动期的 CommandLineRunner）写入，而 SchemaBaselineIT 只跑 Flyway、不启 Spring，
-- 空库里根本没有 SYSTEM_ADMIN 角色行。那条断言会让新装库的迁移直接失败。
-- 「授权是否生效」由代码侧测试与真实库验收承担（见 ADR-M010 约束）。
do $$
declare
  n_perm bigint;
begin
  select count(*) into n_perm from sys_permission where code = 'workflow:definition:manage';
  if n_perm <> 1 then
    raise exception 'V14 失败：权限点 workflow:definition:manage 应恰好 1 条，实际 % 条', n_perm;
  end if;

  -- 「授权是否生效」由 DataInitializer#grantDefinitionManage 在 Spring 启动期补授，
  -- 由代码侧测试与真实库验收承担（见 ADR-M010 约束）；Flyway 阶段绝不在此断言授权，
  -- 否则任何「已有 SYSTEM_ADMIN 角色、但首次执行本迁移」的库都会启动失败。
  raise notice 'V14 ok: 权限点 workflow:definition:manage 已就位（角色授权由 DataInitializer 在启动期补授）';
end $$;

-- 流程定义：按业务类型区分，支持版本与启用开关
create table process_definition (
  id       bigint generated by default as identity primary key,
  code     varchar(32)  not null unique,
  name     varchar(64)  not null,
  biz_type varchar(32)  not null,
  version  integer      not null,
  enabled  boolean      not null
);

-- 流程节点定义
create table process_node (
  id             bigint generated by default as identity primary key,
  definition_id  bigint       not null,
  seq            integer      not null,
  node_type      varchar(16)  not null,
  name           varchar(64)  not null,
  assignee_type  varchar(16),
  assignee_expr  varchar(128),
  multi_type     varchar(16),
  condition_expr varchar(256)
);

-- 流程实例
create table process_instance (
  id               bigint generated by default as identity primary key,
  definition_id    bigint       not null,
  biz_type         varchar(32)  not null,
  biz_id           bigint,
  title            varchar(128) not null,
  initiator        varchar(32)  not null,
  project_id       bigint,
  status           varchar(16)  not null,
  variables        text,
  current_node_seq integer,
  created_at       timestamp    not null,
  finished_at      timestamp
);

-- 运行时任务
create table process_task (
  id          bigint generated by default as identity primary key,
  instance_id bigint       not null,
  node_seq    integer      not null,
  node_name   varchar(64)  not null,
  assignee    varchar(64)  not null,
  status      varchar(16)  not null,
  comment     varchar(200),
  created_at  timestamp    not null,
  finished_at timestamp
);

create index idx_process_node_definition on process_node (definition_id, seq);
create index idx_process_instance_biz on process_instance (biz_type, biz_id);
create index idx_process_instance_initiator on process_instance (initiator, created_at);
create index idx_process_task_assignee on process_task (assignee, status);
create index idx_process_task_instance on process_task (instance_id, node_seq);

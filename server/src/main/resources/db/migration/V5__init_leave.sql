-- 请假模块（Phase 2 第三批 · 接流程引擎）
-- 数据范围：COMPANY 全表可见；PROJECT 仅本项目部（与花名册一致）。
-- 状态为中文：待审批 / 已批准 / 已驳回，与前端 LeaveRecord.status 对齐。
-- workflow_instance_id 关联 process_instance.id，流程完结/驳回时由业务侧同步状态。

create table leave_record (
  id                   bigint generated by default as identity primary key,
  applicant           varchar(64)  not null,   -- 申请人用户名（取自登录态，防伪造）
  applicant_name      varchar(64),              -- 申请人显示名（冗余，便于列表展示）
  project_id          bigint,                  -- 关联 org_unit.id（type=PROJECT）
  project             varchar(64),             -- 项目部名称（冗余）
  leave_type          varchar(16)  not null,   -- 事假/病假/年假/调休/婚假/产假/护理假/其他
  start_date          varchar(20)  not null,   -- YYYY-MM-DD
  end_date            varchar(20)  not null,   -- YYYY-MM-DD
  days                integer      not null default 0,
  reason              varchar(255),
  status              varchar(16)  not null default '待审批',
  workflow_instance_id bigint,                 -- 关联 process_instance.id
  created_at          timestamp    not null default now(),
  updated_at          timestamp    not null default now()
);

create index idx_leave_project on leave_record (project_id);
create index idx_leave_applicant on leave_record (applicant);
create index idx_leave_instance on leave_record (workflow_instance_id);

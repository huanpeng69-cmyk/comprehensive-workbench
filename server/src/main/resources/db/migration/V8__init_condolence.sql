-- 慰问金审批发放（Phase 2 第六批 · 慰问金模块后端化）
-- 业务表：申请人填报 → 项目工会审批 → 二级单位工会审批 → 已发放 / 已驳回。
-- 流程定义直接落到 migration，确保既有的 WorkflowDataSeeder（仅在 definition 表为空时运行）
-- 不会覆盖它；新库启动时 Flyway 应用本迁移后再由 seeder 补充 leave/payroll/reception 定义。

create table condolence (
  id                      bigint generated by default as identity primary key,
  applicant               varchar(64)    not null,
  applicant_username      varchar(64),
  project_id              bigint,
  project                 varchar(64),
  category                varchar(32)    not null,
  reason                  varchar(255),
  amount                  numeric(12,2)  not null default 0,
  amount_in_words         varchar(64),
  project_union_opinion   varchar(64),
  company_union_opinion   varchar(64),
  status                  varchar(16)    not null,
  workflow_instance_id    bigint,
  created_at              timestamp      not null,
  updated_at              timestamp      not null
);

create index idx_condolence_project on condolence (project_id);
create index idx_condolence_created on condolence (created_at);


-- 党费季度明细（Phase 2 第五批 · 党费模块后端化）
-- 缴费基数关联工资，属敏感数据：查询仅限全公司数据范围角色（服务层闸门 + ACCESS_DENIED 审计）。

create table party_fee (
  id      bigint generated by default as identity primary key,
  name    varchar(64)    not null,
  quarter varchar(16)    not null,
  base1   numeric(12, 2) not null default 0,
  fee1    numeric(12, 2) not null default 0,
  base2   numeric(12, 2) not null default 0,
  fee2    numeric(12, 2) not null default 0,
  base3   numeric(12, 2) not null default 0,
  fee3    numeric(12, 2) not null default 0,
  total   numeric(12, 2) not null default 0
);

create index idx_party_fee_quarter on party_fee (quarter);
